export function cardCost(id) {
  const rank = id.slice(1);
  if (rank === 'A' || rank === 'J') return 1;
  if (rank === 'Q') return 2;
  if (rank === 'K') return 3;
  const n = Number(rank);
  if (n <= 4) return 1;
  if (n <= 7) return 2;
  return n <= 9 ? 3 : 4;
}

export function deckCost({ talent, list }) {
  return list.reduce((sum, id) => sum + cardCost(id), talent ? cardCost(talent) : 0);
}

export function validDeck(deck) {
  return deck && Object.hasOwn(talents, deck.talent) && Array.isArray(deck.list) &&
    deck.list.length === 5 && new Set(deck.list).size === 5 &&
    deck.list.every(id => Object.hasOwn(cards, id)) && deckCost(deck) === 10;
}
